//! Deterministic RDFS / SHACL Turtle exporters (cold, byte-budgeted).

use std::io::{self, Write};

use super::fields::FIELD_DESCRIPTORS;
use super::namespace::{term, VIBE_NS, VIBE_SCHEMA_VERSION};
use super::node_kinds::all_node_kinds;

/// Soft byte budget for generated artifacts (fail closed if exceeded).
#[derive(Debug, Clone, Copy)]
pub struct ExportBudget {
    pub max_bytes: usize,
}

impl Default for ExportBudget {
    fn default() -> Self {
        Self {
            max_bytes: 512 * 1024,
        }
    }
}

const CORE_CLASSES: &[&str] = &[
    "LanguageVersion",
    "Program",
    "Module",
    "AstNode",
    "Declaration",
    "FunctionDeclaration",
    "HookDeclaration",
    "CellDeclaration",
    "FieldDeclaration",
    "MaterialDeclaration",
    "LawDeclaration",
    "Statement",
    "Expression",
    "Pattern",
    "Type",
    "EffectClass",
    "Capability",
    "InvokeId",
    "CapabilityArgument",
    "Budget",
    "SourceSpan",
    "Diagnostic",
    "Receipt",
    "Block",
];

/// Write deterministic RDFS vocabulary Turtle.
pub fn export_rdfs_turtle(w: &mut dyn Write, budget: ExportBudget) -> io::Result<usize> {
    let mut buf = String::new();
    buf.push_str("# Generated by vibe::metamodel::export — do not hand-edit.\n");
    buf.push_str(&format!("# schema_version: {VIBE_SCHEMA_VERSION}\n"));
    buf.push_str("@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .\n");
    buf.push_str("@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n");
    buf.push_str("@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n");
    buf.push_str(&format!("@prefix vibe: <{VIBE_NS}> .\n\n"));
    buf.push_str(&format!(
        "vibe:Metamodel a rdfs:Class ;\n  rdfs:label \"VibeScript metamodel\" ;\n  vibe:schemaVersion \"{VIBE_SCHEMA_VERSION}\" .\n\n"
    ));
    for c in CORE_CLASSES {
        buf.push_str(&format!(
            "vibe:{c} a rdfs:Class ;\n  rdfs:label \"{c}\" ;\n  rdfs:isDefinedBy <{VIBE_NS}> .\n\n"
        ));
    }
    for d in all_node_kinds() {
        buf.push_str(&format!(
            "vibe:nodeKind_{} a vibe:AstNode ;\n  vibe:nodeKind \"{}\" ;\n  rdfs:comment \"{}\" .\n\n",
            d.local_name.replace('.', "_"),
            d.local_name,
            d.rust_path
        ));
        let _ = term(d.rdfs_class_local);
    }
    for f in FIELD_DESCRIPTORS {
        buf.push_str(&format!(
            "vibe:{} a rdf:Property ;\n  rdfs:domain vibe:{} ;\n  rdfs:range {} ;\n  rdfs:label \"{}\" .\n\n",
            f.rdfs_property_local,
            f.domain_class,
            if f.range_hint.starts_with("xsd:") {
                f.range_hint.to_string()
            } else {
                format!("vibe:{}", f.range_hint)
            },
            f.local_name
        ));
    }
    if buf.len() > budget.max_bytes {
        return Err(io::Error::new(
            io::ErrorKind::Other,
            "metamodel RDFS export exceeds budget",
        ));
    }
    w.write_all(buf.as_bytes())?;
    Ok(buf.len())
}

/// Write deterministic SHACL shapes Turtle.
pub fn export_shacl_turtle(w: &mut dyn Write, budget: ExportBudget) -> io::Result<usize> {
    let mut buf = String::new();
    buf.push_str("# Generated by vibe::metamodel::export — do not hand-edit.\n");
    buf.push_str(&format!("# schema_version: {VIBE_SCHEMA_VERSION}\n"));
    buf.push_str("@prefix sh: <http://www.w3.org/ns/shacl#> .\n");
    buf.push_str("@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n");
    buf.push_str(&format!("@prefix vibe: <{VIBE_NS}> .\n\n"));
    buf.push_str(
        "vibe:ProgramShape a sh:NodeShape ;\n  sh:targetClass vibe:Program ;\n  sh:property [\n    sh:path vibe:languageVersion ;\n    sh:minCount 1 ;\n    sh:maxCount 1 ;\n    sh:datatype xsd:string ;\n  ] ;\n  sh:property [\n    sh:path vibe:contains ;\n    sh:class vibe:AstNode ;\n  ] .\n\n",
    );
    buf.push_str(
        "vibe:AstNodeShape a sh:NodeShape ;\n  sh:targetClass vibe:AstNode ;\n  sh:property [\n    sh:path vibe:nodeKind ;\n    sh:minCount 1 ;\n    sh:maxCount 1 ;\n    sh:datatype xsd:string ;\n  ] .\n\n",
    );
    buf.push_str(
        "vibe:FunctionDeclarationShape a sh:NodeShape ;\n  sh:targetClass vibe:FunctionDeclaration ;\n  sh:property [\n    sh:path vibe:hasEffect ;\n    sh:maxCount 1 ;\n    sh:class vibe:EffectClass ;\n  ] ;\n  sh:property [\n    sh:path vibe:hasBudget ;\n    sh:class vibe:Budget ;\n  ] .\n\n",
    );
    if buf.len() > budget.max_bytes {
        return Err(io::Error::new(
            io::ErrorKind::Other,
            "metamodel SHACL export exceeds budget",
        ));
    }
    w.write_all(buf.as_bytes())?;
    Ok(buf.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rdfs_export_deterministic_and_budgeted() {
        let mut a = Vec::new();
        let mut b = Vec::new();
        let n1 = export_rdfs_turtle(&mut a, ExportBudget::default()).unwrap();
        let n2 = export_rdfs_turtle(&mut b, ExportBudget::default()).unwrap();
        assert_eq!(n1, n2);
        assert_eq!(a, b);
        assert!(a.starts_with(b"# Generated"));
        assert!(std::str::from_utf8(&a).unwrap().contains("vibe:Program"));
    }

    #[test]
    fn shacl_export_has_program_shape() {
        let mut buf = Vec::new();
        export_shacl_turtle(&mut buf, ExportBudget::default()).unwrap();
        let s = String::from_utf8(buf).unwrap();
        assert!(s.contains("vibe:ProgramShape"));
        assert!(s.contains("sh:minCount 1"));
    }
}
