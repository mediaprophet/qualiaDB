// ── Pre-computed card data ────────────────────────────────────────────────────

#[derive(Clone, Copy, PartialEq)]
enum BtnKind {
    LaunchContext,
    LaunchQAppStudio,
    LaunchNexus,
    OpenInStudio,
    ComingSoon,
}

struct CardData {
    id: &'static str,
    name: &'static str,
    tagline: &'static str,
    desc: &'static str,
    icon: &'static str,
    status_label: &'static str,
    status_color: &'static str,
    opacity: &'static str,
    btn: BtnKind,
}

// ── Component ─────────────────────────────────────────────────────────────────

#[component]
