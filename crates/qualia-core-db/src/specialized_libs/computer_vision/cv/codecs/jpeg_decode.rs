//! JPEG decode → packed RGB8. Cold path (`Vec` allowed).
//!
//! Decode only: `jpeg-decoder` ships no encoder, so there is deliberately no
//! `encode_jpeg` counterpart. Encode via [`super::png_encode::encode_png`] for
//! a lossless round-trippable format.

use super::super::error::CvError;

/// Decode a JPEG byte stream into packed RGB8 plus dimensions.
///
/// Returns `(rgb, width, height)` where `rgb.len() == width * height * 3`.
/// Baseline colour JPEGs decode directly to RGB24. Grayscale (`L8`) is
/// replicated across R/G/B. 16-bit luma (`L16`) and CMYK (`CMYK32`) are not
/// supported here and map to [`CvError::InvalidParameter`] (fail closed) — the
/// crate has no `UnsupportedFormat` variant.
///
/// Cold path only. Any decode failure maps to a [`CvError`] — never panics.
pub fn decode_jpeg(bytes: &[u8]) -> Result<(Vec<u8>, u32, u32), CvError> {
    if bytes.is_empty() {
        return Err(CvError::EmptyInput);
    }

    let mut decoder = jpeg_decoder::Decoder::new(bytes);
    let pixels = decoder.decode().map_err(|_| CvError::InvalidParameter)?;
    let info = decoder.info().ok_or(CvError::InvalidParameter)?;

    let width = info.width as u32;
    let height = info.height as u32;
    if width == 0 || height == 0 {
        return Err(CvError::EmptyInput);
    }

    let px = (width as usize)
        .checked_mul(height as usize)
        .ok_or(CvError::InvalidParameter)?;

    match info.pixel_format {
        jpeg_decoder::PixelFormat::RGB24 => {
            let need = px.checked_mul(3).ok_or(CvError::InvalidParameter)?;
            if pixels.len() < need {
                return Err(CvError::BufferTooSmall);
            }
            let mut rgb = pixels;
            rgb.truncate(need);
            Ok((rgb, width, height))
        }
        jpeg_decoder::PixelFormat::L8 => {
            if pixels.len() < px {
                return Err(CvError::BufferTooSmall);
            }
            let mut rgb = vec![0u8; px * 3];
            for i in 0..px {
                let g = pixels[i];
                let d = i * 3;
                rgb[d] = g;
                rgb[d + 1] = g;
                rgb[d + 2] = g;
            }
            Ok((rgb, width, height))
        }
        // 16-bit grayscale and CMYK are not handled: fail closed.
        jpeg_decoder::PixelFormat::L16 | jpeg_decoder::PixelFormat::CMYK32 => {
            Err(CvError::InvalidParameter)
        }
    }
}

