    #[test]
    fn baseline_jpeg_decodes_to_correct_dims() {
        let (rgb, w, h) = decode_jpeg(RED_8X8_JPEG).expect("decode ok");
        assert_eq!((w, h), (8, 8));
        assert_eq!(rgb.len(), (w * h * 3) as usize);
        // Solid red source (200,40,40): the centre pixel must read reddish.
        let c = ((3 * 8 + 3) * 3) as usize;
        let (r, g, b) = (rgb[c], rgb[c + 1], rgb[c + 2]);
        assert!(
            r > g && r > b,
            "centre pixel should be reddish: {r},{g},{b}"
        );
    }

    #[test]
    fn malformed_jpeg_fails_closed() {
        let garbage = [0xff_u8, 0xd8, 0x00, 0x11, 0x22, 0x33, 0x44, 0x55];
        let r = decode_jpeg(&garbage);
        assert!(r.is_err(), "malformed JPEG must return Err, got {:?}", r);
    }

    #[test]
    fn empty_jpeg_is_empty_input() {
        assert_eq!(decode_jpeg(&[]), Err(CvError::EmptyInput));
    }
